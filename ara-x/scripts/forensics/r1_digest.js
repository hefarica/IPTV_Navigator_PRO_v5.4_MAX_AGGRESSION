#!/usr/bin/env node
'use strict';
/**
 * R1 · Compact digest of an r1_analyze.js findings JSON.
 * Usage: node r1_digest.js <findings.json> [--top N]
 */
const fs = require('node:fs');

const p = process.argv[2];
const topN = (() => { const i = process.argv.indexOf('--top'); return i === -1 ? 20 : Number(process.argv[i + 1]); })();
const j = JSON.parse(fs.readFileSync(p, 'utf8'));
const L = [];
const push = (s) => L.push(s);
const kv = (k, v) => push(`  ${k}: ${typeof v === 'object' ? JSON.stringify(v) : v}`);
const top = (label, obj, n = topN) => {
  if (!obj || typeof obj !== 'object') return kv(label, obj);
  const t = obj.top || [];
  push(`  ${label} (distinct=${obj.total_distinct ?? Object.keys(obj).length}): ` +
    t.slice(0, n).map((x) => `${x.key}×${x.count}`).join(' · '));
};

push(`### ${j.label}`);
kv('file', j.file);
kv('bytes', j.bytes);
kv('lines', j.lines);
kv('empty_lines', j.empty_lines);
kv('crlf_lines', j.crlf_lines);
kv('bom', j.bom);
kv('last_byte_hex', j.last_byte_hex_hex || j.last_byte_hex);
kv('final_newline', j.final_newline);
kv('header.lines', j.header.lines);
kv('header.tag_count', Object.keys(j.header.tags || {}).length);
kv('elapsed_ms', j.elapsed_ms);
push('');
push('-- TAG COUNTS (top 40) --');
for (const [k, v] of Object.entries(j.tag_counts || {}).slice(0, 40)) push(`  ${k} = ${v}`);
push(`  … total distinct tags = ${Object.keys(j.tag_counts || {}).length}`);
push('');
push('-- TAG BYTES (top 15) --');
for (const [k, v] of Object.entries(j.tag_bytes || {}).slice(0, 15)) push(`  ${k} = ${v} B (${(v / 1048576).toFixed(1)} MiB)`);
push('');
push('-- CHANNELS --');
kv('count', j.channels.count);
kv('lines_per_block', j.channels.lines_per_block);
kv('bytes_per_block', j.channels.bytes_per_block);
kv('avg_lines', (j.channels.lines_per_block.sum / Math.max(1, j.channels.count)).toFixed(2));
kv('avg_bytes', (j.channels.bytes_per_block.sum / Math.max(1, j.channels.count)).toFixed(1));
kv('blocks_missing_url', j.channels.blocks_missing_url);
kv('blocks_multi_url', j.channels.blocks_multi_url);
kv('blocks_zero_stream_inf', j.channels.blocks_zero_stream_inf);
kv('blocks_multi_stream_inf', j.channels.blocks_multi_stream_inf);
kv('blocks_multi_extinf', j.channels.blocks_multi_extinf);
kv('stream_inf_not_adjacent_to_url', j.channels.stream_inf_not_adjacent_to_url);
kv('blocks_stream_inf_adjacent_ok', j.channels.blocks_stream_inf_adjacent_ok);
kv('stream_inf_not_followed_by_uri', j.channels.stream_inf_not_followed_by_uri);
top('stream_inf_per_block', j.channels.stream_inf_per_block, 8);
top('shapes', j.channels.shapes, 6);
push('');
push('-- EXTINF --');
top('durations', j.extinf.durations, 5);
push(`  attrs (${Object.keys(j.extinf.attrs || {}).length}): ` + Object.entries(j.extinf.attrs || {}).slice(0, 30).map(([k, v]) => `${k}×${v}`).join(' · '));
push(`  attr_missing: ${JSON.stringify(j.extinf.attr_missing)}`);
push(`  empty_attr_values: ${JSON.stringify(j.extinf.empty_attr_values)}`);
push('');
push('-- STREAM-INF --');
top('resolution', j.stream_inf.resolution, 10);
top('codecs', j.stream_inf.codecs, 10);
top('bandwidth', j.stream_inf.bandwidth, 10);
top('avg_bandwidth', j.stream_inf.avg_bandwidth, 6);
top('video_range', j.stream_inf.video_range, 6);
top('frame_rate', j.stream_inf.frame_rate, 6);
top('hdcp', j.stream_inf.hdcp, 6);
top('supplemental', j.stream_inf.supplemental, 6);
kv('missing', j.stream_inf.missing);
push('');
push('-- PROFILE / CODEC-FAMILY / FPS --');
push(`  profile: ${JSON.stringify(j.profile)}`);
push(`  codec_family: ${JSON.stringify(j.codec_family)}`);
push(`  fps_attr: ${JSON.stringify(j.fps_attr)}`);
push('');
push('-- PLACEMENT --');
push(`  media_only_in_master: ${JSON.stringify(j.placement.media_only_in_master)}`);
push(`  master_only_ok: ${JSON.stringify(j.placement.master_only_ok)}`);
push(`  both: ${JSON.stringify(j.placement.both)}`);
push(`  media_with_uri: ${j.media_with_uri} · iframe_stream_inf: ${j.iframe_stream_inf} · iframe_with_uri: ${j.iframe_stream_inf_with_uri}`);
push('');
push('-- LL-HLS --');
push(`  ${JSON.stringify(j.llhls)}`);
push('');
push('-- APES DECLARATIONS --');
push(`  4kfalse=${j.apes['4kfalse']} 8kfake=${j.apes['8kfake']} l153_decl=${j.apes.l153_decl} pq_decl=${j.apes.pq_decl}`);
push(`  kodi_hdr_bt2020=${j.apes.kodi_hdr_bt2020} kodi_hdr_sdr=${j.apes.kodi_hdr_sdr} hlg=${j.apes.hlg_true} dv=${j.apes.dv_true} lcevc=${j.apes.lcevc} ai_sr=${j.apes.ai_sr} ai_fi=${j.apes.ai_fi} drm_L1=${j.apes.drm_L1}`);
push(`  streaminf_res_2160=${j.apes.streaminf_resolution_2160} x_res_1080=${j.apes.x_resolution_1080} x_res_2160=${j.apes.x_resolution_2160}`);
top('8kfake_attrs', j.apes['8kfake_attrs'], 6);
top('codec_full', j.apes.codec_full, 8);
push(`  resolution_contradictions: ${JSON.stringify(j.resolution_contradictions)}`);
push('');
push('-- EXT HTTP --');
kv('count', j.ext_http.count);
kv('json_valid', j.ext_http.json_valid);
kv('json_invalid', j.ext_http.json_invalid);
kv('max_len', j.ext_http.max_len);
kv('channels_with_toxic', j.ext_http.channels_with_toxic);
kv('toxic', j.ext_http.toxic);
top('header_count_dist', j.ext_http.header_count_dist, 8);
top('key_presence', j.ext_http.key_presence, 12);
for (const [k, v] of Object.entries(j.ext_http.value_dist || {})) top(`value_dist[${k}]`, v, 8);
push('');
push('-- DEDUP --');
kv('url_exact_dups', j.dedup.url_exact_dups);
kv('url_norm_dups', j.dedup.url_norm_dups);
kv('tvgid_dups', j.dedup.tvgid_dups);
kv('name_group_dups', j.dedup.name_group_dups);
kv('name_dups', j.dedup.name_dups);
push('');
push('-- URLS --');
top('schemes', j.urls.schemes, 5);
top('hosts', j.urls.hosts, 12);
top('logo_hosts', j.logos.hosts, 6);
top('groups', j.groups, 12);
top('countries', j.countries, 12);
top('regions', j.regions, 6);
push('');
push('-- SESSION IDS --');
kv('distinct_sid', j.session_ids.distinct_sid);
kv('distinct_nonce', j.session_ids.distinct_nonce);
kv('distinct_spoof_ip', j.session_ids.distinct_spoof_ip);
kv('spoof_ip_sample', j.session_ids.spoof_ip_sample);
push('');
push('-- FOOTER / LAST LINES --');
kv('declared_channels', j.footer.declared_channels);
kv('validated', j.footer.validated);
kv('scorecard', j.footer.scorecard);
push('  last_lines:');
for (const l of j.last_lines || []) push('    | ' + (l.length > 200 ? l.slice(0, 200) + '…' : l));

console.log(L.join('\n'));
